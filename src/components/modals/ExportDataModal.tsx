'use client';

import React, { useState, useEffect } from 'react';
import { X } from 'lucide-react';

export type ExportFormatType = 'pdf' | 'xls' | 'csv';

export interface ExportDataModalProps {
  isOpen: boolean;
  onClose: () => void;
  title?: string;
  filenamePrefix?: string;
  columns: string[];
  rows: (string | number)[][];
  onSuccess?: (format: ExportFormatType) => void;
}

export function ExportDataModal({
  isOpen,
  onClose,
  title = 'All Locations',
  filenamePrefix = 'local_marketing_all_locations',
  columns,
  rows,
  onSuccess,
}: ExportDataModalProps) {
  const [selectedFormat, setSelectedFormat] = useState<ExportFormatType>('pdf');
  const [isExporting, setIsExporting] = useState(false);

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape' && isOpen) {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!isOpen) return null;

  // Generate compliant PDF 1.4 Blob
  const createPdfBlob = (): Blob => {
    const sanitize = (text: any) =>
      String(text ?? '')
        .replace(/[\\()]/g, '')
        .replace(/[^\x20-\x7E]/g, ' ');

    const dateStr = new Date().toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    });

    let stream = '';
    // Document Title
    stream += 'BT\n/F1 16 Tf\n50 745 Td\n';
    stream += `(SE Ranking - ${sanitize(title)}) Tj\nET\n`;

    // Subtitle & metadata
    stream += 'BT\n/F2 9 Tf\n50 730 Td\n';
    stream += `(Local Marketing Report | Export Date: ${sanitize(dateStr)} | Total Records: ${rows.length}) Tj\nET\n`;

    // Header divider line
    stream += '0.3 w\n50 720 m 560 720 l S\n';

    // Calculate column widths
    const colCount = Math.max(columns.length, 1);
    const availableWidth = 510;
    const colWidth = Math.floor(availableWidth / colCount);

    let y = 702;

    // Table Header Row
    stream += 'BT\n/F1 10 Tf\n';
    columns.forEach((col, idx) => {
      const x = 50 + idx * colWidth;
      stream += `1 0 0 1 ${x} ${y} Tm (${sanitize(col)}) Tj\n`;
    });
    stream += 'ET\n';

    // Header underline
    stream += '0.5 w\n';
    stream += `50 ${y - 5} m 560 ${y - 5} l S\n`;
    y -= 20;

    // Table Data Rows
    stream += 'BT\n/F2 8.5 Tf\n';
    rows.slice(0, 36).forEach((row) => {
      row.forEach((cell, idx) => {
        const x = 50 + idx * colWidth;
        const maxChars = Math.max(8, Math.floor(colWidth / 5.5));
        const text = sanitize(String(cell)).substring(0, maxChars);
        stream += `1 0 0 1 ${x} ${y} Tm (${text}) Tj\n`;
      });
      y -= 16;
    });
    stream += 'ET\n';

    // Bottom Footer
    stream += '0.2 w\n50 45 m 560 45 l S\n';
    stream += 'BT\n/F2 8 Tf\n50 32 Td\n';
    stream += '(Generated by SE Ranking White Label | Certified Report Export) Tj\nET\n';

    const streamLen = stream.length;
    const objects: string[] = [];
    objects[1] = '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n';
    objects[2] = '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n';
    objects[3] =
      '3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>\nendobj\n';
    objects[4] = '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n';
    objects[5] = '5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n';
    objects[6] = `6 0 obj\n<< /Length ${streamLen} >>\nstream\n${stream}\nendstream\nendobj\n`;

    let pdf = '%PDF-1.4\n';
    const offsets: number[] = [];
    for (let i = 1; i <= 6; i++) {
      offsets[i] = pdf.length;
      pdf += objects[i];
    }

    const xrefOffset = pdf.length;
    pdf += 'xref\n0 7\n0000000000 65535 f \n';
    for (let i = 1; i <= 6; i++) {
      pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
    }
    pdf += `trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

    return new Blob([pdf], { type: 'application/pdf' });
  };

  // Generate Excel (.xls) HTML/XML Table Blob
  const createExcelBlob = (): Blob => {
    const html = `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
<head>
<meta http-equiv="Content-Type" content="text/html; charset=utf-8">
<!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet><x:Name>Locations</x:Name><x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions></x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]-->
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; font-size: 11pt; }
  h2 { color: #1E293B; margin-bottom: 4px; }
  .meta { color: #64748B; font-size: 10pt; margin-bottom: 12px; }
  table { border-collapse: collapse; width: 100%; }
  th { background-color: #2F3B4C; color: #FFFFFF; font-weight: bold; border: 1px solid #CBD5E1; padding: 10px 14px; text-align: left; }
  td { border: 1px solid #E2E8F0; padding: 8px 14px; color: #1E293B; }
  tr:nth-child(even) { background-color: #F8FAFC; }
  .footer { margin-top: 16px; font-size: 9pt; color: #94A3B8; }
</style>
</head>
<body>
  <h2>SE Ranking - ${title}</h2>
  <div class="meta">Export Date: ${new Date().toLocaleDateString()} | Total Records: ${rows.length}</div>
  <table>
    <thead>
      <tr>
        ${columns.map((c) => `<th>${c}</th>`).join('')}
      </tr>
    </thead>
    <tbody>
      ${rows
        .map(
          (r) =>
            `<tr>${r.map((cell) => `<td>${cell !== null && cell !== undefined ? String(cell) : ''}</td>`).join('')}</tr>`
        )
        .join('')}
    </tbody>
  </table>
  <div class="footer">Generated by SE Ranking White Label</div>
</body>
</html>`;

    return new Blob([html], { type: 'application/vnd.ms-excel;charset=utf-8;' });
  };

  // Generate CSV (.csv) Blob with UTF-8 BOM
  const createCsvBlob = (): Blob => {
    const escapeCell = (val: any) => {
      const s = String(val ?? '').replace(/"/g, '""');
      return `"${s}"`;
    };

    const headerRow = columns.map(escapeCell).join(',');
    const dataRows = rows.map((r) => r.map(escapeCell).join(',')).join('\r\n');
    const csvContent = '\uFEFF' + headerRow + '\r\n' + dataRows;

    return new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  };

  const handleExecuteExport = () => {
    setIsExporting(true);
    const dateStamp = new Date().toISOString().split('T')[0];

    try {
      let blob: Blob;
      let extension: string;

      if (selectedFormat === 'pdf') {
        blob = createPdfBlob();
        extension = 'pdf';
      } else if (selectedFormat === 'xls') {
        blob = createExcelBlob();
        extension = 'xls';
      } else {
        blob = createCsvBlob();
        extension = 'csv';
      }

      if (typeof window !== 'undefined' && typeof window.URL?.createObjectURL === 'function') {
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${filenamePrefix}_${dateStamp}.${extension}`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);

        setTimeout(() => {
          URL.revokeObjectURL(url);
        }, 1500);
      }

      if (onSuccess) {
        onSuccess(selectedFormat);
      }
    } catch (err) {
      console.error('Export download error:', err);
    } finally {
      setIsExporting(false);
      onClose();
    }
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4 animate-in fade-in duration-150"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <div className="bg-white rounded-lg max-w-[500px] w-full p-6 shadow-2xl relative space-y-5 animate-in zoom-in-95 duration-150 border border-gray-100">
        {/* Modal Header */}
        <div className="flex items-center justify-between pb-1">
          <h2 className="text-[17px] font-bold text-[#1E293B]">Export data</h2>
          <button
            type="button"
            onClick={onClose}
            className="p-1 rounded text-gray-400 hover:text-gray-600 transition-colors cursor-pointer"
            title="Close"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Format Selection Section */}
        <div className="space-y-2.5">
          <div className="text-xs font-semibold text-[#1E293B]">Format:</div>

          {/* 3 Selectable Format Cards */}
          <div className="grid grid-cols-3 gap-3">
            {/* Card 1: PDF (.pdf) */}
            <div
              onClick={() => setSelectedFormat('pdf')}
              className={`p-3.5 rounded-md border flex flex-col items-center justify-center text-center cursor-pointer transition-all h-[115px] select-none ${
                selectedFormat === 'pdf'
                  ? 'bg-[#504A70] text-white border-[#504A70] shadow-xs'
                  : 'bg-white text-[#1E293B] border-[#CBD5E1] hover:border-gray-400'
              }`}
            >
              {/* PDF Icon */}
              <div className="mb-2">
                <svg
                  className="w-7 h-7"
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                >
                  <path
                    d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"
                    fill={selectedFormat === 'pdf' ? '#FFFFFF' : '#F1F5F9'}
                    stroke={selectedFormat === 'pdf' ? '#FFFFFF' : '#CBD5E1'}
                  />
                  <polyline
                    points="14 2 14 8 20 8"
                    fill={selectedFormat === 'pdf' ? '#504A70' : '#E2E8F0'}
                    stroke={selectedFormat === 'pdf' ? '#FFFFFF' : '#94A3B8'}
                  />
                  <path
                    d="M9 13h6M9 17h3"
                    stroke={selectedFormat === 'pdf' ? '#504A70' : '#E53935'}
                    strokeWidth="2.5"
                  />
                </svg>
              </div>
              <span className="text-xs font-bold leading-tight">PDF (.pdf)</span>
            </div>

            {/* Card 2: Excel (.xls) */}
            <div
              onClick={() => setSelectedFormat('xls')}
              className={`p-3.5 rounded-md border flex flex-col items-center justify-center text-center cursor-pointer transition-all h-[115px] select-none ${
                selectedFormat === 'xls'
                  ? 'bg-[#504A70] text-white border-[#504A70] shadow-xs'
                  : 'bg-white text-[#1E293B] border-[#CBD5E1] hover:border-gray-400'
              }`}
            >
              {/* Excel Green Icon */}
              <div className="mb-2">
                <div
                  className={`w-7 h-7 rounded flex items-center justify-center font-bold text-xs shadow-2xs ${
                    selectedFormat === 'xls' ? 'bg-white text-[#107C41]' : 'bg-[#107C41] text-white'
                  }`}
                >
                  <span className="font-extrabold tracking-tighter">X</span>
                </div>
              </div>
              <span className="text-xs font-bold leading-tight">Excel (.xls)</span>
              <span
                className={`text-[11px] italic mt-1 ${
                  selectedFormat === 'xls' ? 'text-white/80' : 'text-[#8C9BA5]'
                }`}
              >
                Max. 10K rows
              </span>
            </div>

            {/* Card 3: CSV (.csv) */}
            <div
              onClick={() => setSelectedFormat('csv')}
              className={`p-3.5 rounded-md border flex flex-col items-center justify-center text-center cursor-pointer transition-all h-[115px] select-none ${
                selectedFormat === 'csv'
                  ? 'bg-[#504A70] text-white border-[#504A70] shadow-xs'
                  : 'bg-white text-[#1E293B] border-[#CBD5E1] hover:border-gray-400'
              }`}
            >
              {/* CSV Blue Icon */}
              <div className="mb-2">
                <div
                  className={`w-7 h-7 rounded flex items-center justify-center font-bold text-[9px] shadow-2xs tracking-tighter ${
                    selectedFormat === 'csv' ? 'bg-white text-[#7C3AED]' : 'bg-[#7C3AED] text-white'
                  }`}
                >
                  <span className="font-black">CSV</span>
                </div>
              </div>
              <span className="text-xs font-bold leading-tight">CSV (.csv)</span>
              <span
                className={`text-[11px] italic mt-1 ${
                  selectedFormat === 'csv' ? 'text-white/80' : 'text-[#8C9BA5]'
                }`}
              >
                No limits
              </span>
            </div>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="flex items-center justify-end gap-2.5 pt-3">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2 rounded-[4px] border border-[#CBD5E1] text-xs font-bold uppercase tracking-wider text-[#475569] hover:bg-gray-50 transition-colors cursor-pointer"
          >
            CANCEL
          </button>
          <button
            type="button"
            disabled={isExporting}
            onClick={handleExecuteExport}
            className="px-6 py-2 rounded-[4px] bg-[#7C3AED] hover:bg-[#6D28D9] text-white text-xs font-bold uppercase tracking-wider shadow-2xs transition-colors cursor-pointer disabled:opacity-50"
          >
            {isExporting ? 'EXPORTING...' : 'EXPORT'}
          </button>
        </div>
      </div>
    </div>
  );
}
